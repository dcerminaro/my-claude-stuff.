// Generates Caesar's voiceover with ElevenLabs, plus exact word and letter
// timings used to sync subtitles, mouth movement and cuts.
//
// Run:            node scripts/make-voice.mjs voice/<film-id>.json
// Rough preview:  node scripts/make-voice.mjs voice/<film-id>.json --placeholder
//                 (no API call, estimated timings, no audio)
// List voices:    node scripts/make-voice.mjs --voices
//
// Writes: public/voice/<film-id>/<line-id>.mp3 and src/voice/<film-id>.ts
//
// API key: in the cloud the network proxy adds it automatically. On your own
// computer, set ELEVENLABS_API_KEY in your terminal before running.
// In the cloud, run with NODE_USE_ENV_PROXY=1 so Node uses the proxy.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const API = "https://api.elevenlabs.io";
const key = process.env.ELEVENLABS_API_KEY ?? "added-by-proxy";
const headers = { "xi-api-key": key, "Content-Type": "application/json" };

const args = process.argv.slice(2);

if (args.includes("--voices")) {
  const res = await fetch(`${API}/v1/voices`, { headers });
  if (!res.ok) throw new Error(`ElevenLabs ${res.status}: ${await res.text()}`);
  const { voices } = await res.json();
  for (const v of voices) {
    console.log(`${v.voice_id}  ${v.name.padEnd(28)} ${Object.values(v.labels ?? {}).join(", ")}`);
  }
  process.exit(0);
}

const scriptPath = args.find((a) => a.endsWith(".json"));
if (!scriptPath) throw new Error("Usage: node scripts/make-voice.mjs voice/<film-id>.json [--placeholder]");
const placeholder = args.includes("--placeholder");
const script = JSON.parse(fs.readFileSync(path.join(root, scriptPath), "utf8"));
const film = script.film;

/** estimate timings when there is no audio yet */
const estimate = (text) => {
  const chars = [];
  let t = 0;
  for (const ch of text) {
    let d = 0.065;
    if (ch === " ") d = 0.05;
    if (",;".includes(ch)) d = 0.2;
    if (".!?".includes(ch)) d = 0.32;
    chars.push([ch, +t.toFixed(3), +(t + d).toFixed(3)]);
    t += d;
  }
  return chars;
};

const toWords = (chars) => {
  const words = [];
  let cur = null;
  for (const [ch, s, e] of chars) {
    if (ch === " ") {
      if (cur) words.push(cur);
      cur = null;
      continue;
    }
    if (!cur) cur = { text: "", start: s, end: e };
    cur.text += ch;
    cur.end = e;
  }
  if (cur) words.push(cur);
  return words;
};

const outAudioDir = path.join(root, "public", "voice", film);
fs.mkdirSync(outAudioDir, { recursive: true });

const lines = [];
for (let i = 0; i < script.lines.length; i++) {
  const line = script.lines[i];
  let chars;
  let src = null;
  if (placeholder) {
    chars = estimate(line.text);
  } else {
    const url = `${API}/v1/text-to-speech/${script.voiceId}/with-timestamps?output_format=mp3_44100_128`;
    const body = {
      text: line.text,
      model_id: script.modelId,
      voice_settings: { ...script.settings, ...(line.settings ?? {}) },
      previous_text: script.lines[i - 1]?.text,
      next_text: script.lines[i + 1]?.text,
    };
    const res = await fetch(url, { method: "POST", headers, body: JSON.stringify(body) });
    if (!res.ok) throw new Error(`ElevenLabs ${res.status} on "${line.id}": ${await res.text()}`);
    const data = await res.json();
    const file = `${line.id}.mp3`;
    fs.writeFileSync(path.join(outAudioDir, file), Buffer.from(data.audio_base64, "base64"));
    const al = data.alignment;
    chars = al.characters.map((c, k) => [c, al.character_start_times_seconds[k], al.character_end_times_seconds[k]]);
    src = `voice/${film}/${file}`;
    console.log(`voiced ${line.id}: "${line.text}"`);
  }
  const duration = +((chars.at(-1)?.[2] ?? 0) + 0.12).toFixed(3);
  lines.push({ id: line.id, text: line.text, src, duration, chars, words: toWords(chars) });
}

const ts = `// Generated by scripts/make-voice.mjs from ${scriptPath}. Do not edit by hand.
import type { VoiceTrack } from "./types";

export const voice: VoiceTrack = ${JSON.stringify({ film, placeholder, voiceId: script.voiceId, lines }, null, 2)};
`;
const outTs = path.join(root, "src", "voice", `${film}.ts`);
fs.writeFileSync(outTs, ts);
console.log(`wrote ${path.relative(root, outTs)}${placeholder ? " (placeholder timings, no audio)" : ""}`);
